// The Confluence page for one FDA recall: what is wrong, what to do, which hospital devices are
// affected, and the Jira tasks that track the work. Pure functions (no Forge imports), so they are
// unit tested with plain Node.
//
// The body is Confluence "storage format" (XHTML). EVERY piece of text that comes from the FDA or
// from the hospital's device list is escaped first, so a recall or device name can never inject markup.
import { CLASS_MEANINGS, buildActionSteps } from './agentTools.js';
import { pairKey, recallRecordUrl, FDA_RECALL_DATABASE_URL, dueDaysFor } from './taskRules.js';

export function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

// One page per recall, found again by this exact title.
export function recallPageTitle(recallNumber) {
  return `FDA recall ${recallNumber}`;
}

// Jira issue keys look like ABC-123. Anything else is shown as plain text, never put in a macro.
const ISSUE_KEY = /^[A-Z][A-Z0-9_]*-\d+$/;

// A Jira issue macro, which Confluence renders as a live link with the issue's status.
function taskCell(key) {
  if (!key) return 'no task yet';
  if (!ISSUE_KEY.test(key)) return escapeHtml(key);
  return `<ac:structured-macro ac:name="jira" ac:schema-version="1"><ac:parameter ac:name="key">${key}</ac:parameter></ac:structured-macro>`;
}

const confidenceText = { exact: 'Exact', likely: 'Likely (check manually)' };

// `matches` are the exact/likely matches for this ONE recall (one row per device).
// `taskKeys` maps "recall|device" to an existing Jira key. `info` is the saved per-recall detail
// (status, initiated, reason). `checkedAt` is when the saved check ran.
export function buildRecallPageBody({ matches, info = {}, taskKeys = {}, checkedAt }) {
  const first = matches[0];
  const recallClass = first.recallClass || '';
  const days = dueDaysFor(recallClass);
  const steps = buildActionSteps(recallClass, matches.some((m) => m.confidence === 'likely'));

  const facts = [
    ['Recall class', recallClass ? `Class ${recallClass}` : 'Not stated'],
    ['Recalling firm', first.firm],
    ['Product', first.product],
    ['Reported to FDA', first.date || 'Not stated'],
    ['Recall started', info.initiated || 'Not stated'],
    ['Status', info.status || 'Not stated'],
  ];

  const rows = matches
    .map((m) => {
      const key = taskKeys[pairKey(m.recallNumber, m.deviceId)];
      return `<tr><td>${escapeHtml(m.deviceId)}</td><td>${escapeHtml(m.deviceName)}</td><td>${escapeHtml(m.ward || 'not recorded')}</td><td>${escapeHtml(m.lotOrSerial || 'not recorded')}</td><td>${escapeHtml(confidenceText[m.confidence] || m.confidence)}</td><td>${taskCell(key)}</td></tr>`;
    })
    .join('');

  return [
    `<p><strong>${escapeHtml(CLASS_MEANINGS[recallClass] || 'Class not stated: treat as serious until confirmed.')}</strong></p>`,
    `<table><tbody>${facts.map(([k, v]) => `<tr><th>${escapeHtml(k)}</th><td>${escapeHtml(v)}</td></tr>`).join('')}</tbody></table>`,
    '<h2>What is wrong</h2>',
    `<p>${escapeHtml(info.reason || 'The reason for this recall is not stored in the saved check. Open the FDA record below.')}</p>`,
    '<h2>What to do</h2>',
    `<ol>${steps.map((s) => `<li>${escapeHtml(s)}</li>`).join('')}</ol>`,
    `<p>RecallRadar tasks for a Class ${escapeHtml(recallClass || 'unknown')} recall are due ${days} days after they are created.</p>`,
    '<h2>Affected devices</h2>',
    `<table><tbody><tr><th>Device id</th><th>Device</th><th>Ward</th><th>Serial / lot</th><th>Match</th><th>Jira task</th></tr>${rows}</tbody></table>`,
    '<p>"Exact" means manufacturer, model and serial/lot are all listed in the recall. "Likely" means the model matches but the serial/lot is not listed or not recorded, so check it by hand.</p>',
    '<h2>Sources</h2>',
    `<ul><li><a href="${escapeHtml(recallRecordUrl(first.recallNumber))}">FDA record for ${escapeHtml(first.recallNumber)} (openFDA)</a></li><li><a href="${escapeHtml(FDA_RECALL_DATABASE_URL)}">FDA medical device recall database</a></li></ul>`,
    `<p><em>Generated by RecallRadar from the saved check${checkedAt ? ` of ${escapeHtml(checkedAt)}` : ''}. Re-running it updates this page. Always follow the manufacturer's recall notice.</em></p>`,
  ].join('');
}
